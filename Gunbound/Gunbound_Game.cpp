int Gauge(int x, int y)
{
    HANDLE hConsole = GetStdHandle(STD_OUTPUT_HANDLE);

    int forca = 1;

    char teclaGauge;

    for(int i = 0; ; i++)
    {
        if(i >= 0 && i <= 2 || i >= 15 && i <= 18)
        {
            SetConsoleTextAttribute(hConsole, 2);
        }
        else if(i >= 3 && i <= 5 || i >= 12 && i <= 16)
        {
            SetConsoleTextAttribute(hConsole, 14);
        }
        else if(i >= 6 && i <= 8 || i >= 9 && i <= 12)
        {
            SetConsoleTextAttribute(hConsole, 4);
        }

        gotoxy(x, y);
        cout << "þ";

        if(kbhit())
        {
            teclaGauge = getch();

            if(teclaGauge == 32)
            {
                return forca;
            }
        }

        Sleep(100);

        if(i > 16)
        {
            i = 0;
        }

        if(i < 8)
        {
            forca += 3;
            x++;
        }
        else if(i > 8)
        {
            gotoxy(x, y);
            cout << " ";

            forca -= 3;
            x--;
        }
    }
}

